  if (e.ctrlKey && (k === 'y' || (e.shiftKey && k === 'z'))) { e.preventDefault(); doRedo(); return; }
  if (e.ctrlKey && k === 's') { e.preventDefault(); save(); return; }
  const tools = { v: 'select', s: 'spawn', o: 'object', b: 'building', p: 'prop', e: 'erase', h: 'height', g: 'biome' };
  if (tools[k] && !e.ctrlKey) return setTool(tools[k]);
  if (!sel) return;
  if (k === 'delete' || k === 'backspace') return removeSel();
  if (k === 'escape') { sel = null; refreshInspector(); redraw(); return; }
  const step = e.shiftKey ? 5 : 0.5, mv = { arrowleft: [-step, 0], arrowright: [step, 0], arrowup: [0, -step], arrowdown: [0, step] }[k];
  if (mv && sel.layer !== 'props') { e.preventDefault(); act([sel.layer], () => { const [x, z] = posOf(sel.ref); setPos(sel.ref, x + mv[0], z + mv[1]); }); refreshInspector(); }
