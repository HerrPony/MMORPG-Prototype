// ---------------------------------------------------------------- loading
function load(m) {
  D = m;
  setWorldData(m.scenery);
  D.buildings = clone(m.scenery.buildings);
  initial = { npcs: {}, mobs: {}, quests: {} };
  for (const n of m.npcs) initial.npcs[n.ID] = JSON.stringify(n);
  for (const k of ['mobs', 'quests']) for (const id in m[k]) initial[k][id] = JSON.stringify(strip(k, m[k][id]));
  const bin = Uint8Array.from(atob(m.scenery.props), (c) => c.charCodeAt(0));
  genProps = [];
  const added = new Set((m.edits.propsAdd || []).map((p) => pkey(p.x, p.z)));
  delKeys = new Set((m.edits.propsDel || []).map((p) => pkey(p[0], p[1])));
  for (let o = 0; o + 8 <= bin.length; o += 8) {
    const x = W.x0 + (bin[o + 1] | (bin[o + 2] << 8)) / 40, z = W.z0 + (bin[o + 3] | (bin[o + 4] << 8)) / 40;
    genProps.push({ k: m.scenery.pk[bin[o]], x, z, s: bin[o + 5] / 100, ry: bin[o + 6] / 255 * 6.28, solid: bin[o + 7] / 100, add: added.has(pkey(x, z)) });
  }
  addProps = [];
  for (const p of genProps) if (p.add) addProps.push(p);
  genProps = genProps.filter((p) => !p.add);
  for (const k of ['spawns', 'objects', 'buildings']) dirty[k] = false;
  dirty.props = false; dirty.terrain = false;
  
  resets = new Set(); touched = new Set(); undo = []; redo = [];
  sel = null;
  renderTerrain(); refreshAll();
}

