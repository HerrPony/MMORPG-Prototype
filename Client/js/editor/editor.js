const cellAt = (x, z) => { const i = Math.round((x - W.x0) / W.cell), j = Math.round((z - W.z0) / W.cell); return i >= 0 && j >= 0 && i < W.nx && j < W.nz ? W.hm[j * W.nx + i] : null; };

function place(wx, wz) {
  const x = opt.snap ? Math.round(wx * 2) / 2 : wx, z = opt.snap ? Math.round(wz * 2) / 2 : wz;
  if (tool === 'spawn') act(['spawns'], () => { const o = { mob: opt.mob, x, z }; D.spawns.push(o); sel = { layer: 'spawns', ref: o }; });
  if (tool === 'object') act(['objects'], () => { const o = { obj: opt.obj, x, z }; D.objects.push(o); sel = { layer: 'objects', ref: o }; });
  if (tool === 'building') act(['buildings'], () => { const o = { k: opt.bkind, s: opt.bstyle || undefined, x, z, w: opt.bw, d: opt.bd, h: opt.bh }; D.buildings.push(o); sel = { layer: 'buildings', ref: o }; });
}

// brush tools: props / erase / height / biome
function brush(wx, wz, first) {
  const R = opt.radius;
  if (tool === 'prop') {
    if (!first && Math.hypot(wx - stroke.lastX, wz - stroke.lastZ) < Math.max(1.2, R * 0.45)) return;
    stroke.lastX = wx; stroke.lastZ = wz;
    const n = Math.max(1, Math.round(R * R / 18));
    for (let i = 0; i < (R < 2 ? 1 : n); i++) {
      const a = Math.random() * 6.28, r = R < 2 ? 0 : Math.sqrt(Math.random()) * R;
      const x = wx + Math.cos(a) * r, z = wz + Math.sin(a) * r;
      const q = { k: opt.pkind, x: Math.round(x * 40) / 40, z: Math.round(z * 40) / 40, s: +(0.8 + Math.random() * 0.9).toFixed(2), ry: Math.random() * 6.28, solid: DEF_SOLID[opt.pkind] || 0, add: true };
      addProps.push(q);
    }
  } else if (tool === 'erase') {
    for (const list of [genProps, addProps]) for (const p of list) {
      if (p.del || Math.hypot(p.x - wx, p.z - wz) > R) continue;
      if (p.add) { p.del = true; } else { p.del = true; delKeys.add(pkey(p.x, p.z)); }
    }
    addProps = addProps.filter((p) => !p.del);
  } else if (tool === 'height' || tool === 'biome') terrainBrush(wx, wz, first);
  redraw();
}
const DEF_SOLID = { pine: 0.5, oak: 0.5, dead: 0.4, snowpine: 0.5, cactus: 0.5, palm: 0.4, rock: 0.7, bush: 0.4, jtree: 0.7, bamboo: 0.4, sakura: 0.5, mesapillar: 1.3, charred: 0.4, obsidian: 0.7 };

function terrainBrush(wx, wz, first) {
  const ci = (wx - W.x0) / W.cell, cj = (wz - W.z0) / W.cell, rc = opt.radius / W.cell;
  const i0 = Math.max(1, Math.floor(ci - rc)), i1 = Math.min(W.nx - 2, Math.ceil(ci + rc)), j0 = Math.max(1, Math.floor(cj - rc)), j1 = Math.min(W.nz - 2, Math.ceil(cj + rc));
  if (first && tool === 'height' && opt.hmode === 'flatten') stroke.level = W.hm[Math.round(cj) * W.nx + Math.round(ci)];
  const tmp = [];
  for (let j = j0; j <= j1; j++) for (let i = i0; i <= i1; i++) {
    const d = Math.hypot(i - ci, j - cj) / rc; if (d > 1) continue;
    const f = 0.5 + 0.5 * Math.cos(d * Math.PI), idx = j * W.nx + i, h = W.hm[idx], b = W.bm[idx];
    let nh = h, nb = b;
    if (tool === 'biome') { if (d <= 1) nb = opt.biome; }
    else if (opt.hmode === 'raise') nh = h + 0.35 * opt.strength * f;
    else if (opt.hmode === 'lower') nh = h - 0.35 * opt.strength * f;
    else if (opt.hmode === 'flatten') nh = h + (stroke.level - h) * Math.min(1, f * opt.strength);
    else { const a = (W.hm[idx - 1] + W.hm[idx + 1] + W.hm[idx - W.nx] + W.hm[idx + W.nx] + h) / 5; nh = h + (a - h) * Math.min(1, f * opt.strength * 1.5); }
    nh = Math.round(nh * 20) / 20;
    if (nh !== h || nb !== b) tmp.push([idx, h, b, nh, nb]);
  }
  for (const [idx, h, b, nh, nb] of tmp) {
    const old = stroke.terr.get(idx);
    stroke.terr.set(idx, [old ? old[0] : [h, b], [nh, nb]]);
    W.hm[idx] = nh; W.bm[idx] = nb; touched.add(idx);
  }
  if (tmp.length) { dirty.terrain = true; renderTerrain([i0 - 1, j0 - 1, i1 + 1, j1 + 1]); updateDirty(); }
}

