// ---------------------------------------------------------------- undo
function snapshot(names) { const o = {}; for (const n of names) o[n] = clone(n === 'props' ? { a: addProps, d: [...delKeys], g: genProps.filter((p) => p.del).map((p) => pkey(p.x, p.z)) } : LAYER_GET[n]()); return o; }
function restore(o) {
  for (const n in o) {
    if (n === 'props') {
      addProps = clone(o.props.a); delKeys = new Set(o.props.d); const g = new Set(o.props.g);
      for (const p of genProps) p.del = g.has(pkey(p.x, p.z));
    } else D[n] = clone(o[n]);
    markDirty(n);
  }
  sel = null; refreshAll();
}
function act(names, fn) { // runs fn as one undoable step over the given layers
  const before = snapshot(names); fn(); const after = snapshot(names);
  undo.push({ before, after, terrain: null }); if (undo.length > 80) undo.shift(); redo = [];
  for (const n of names) markDirty(n);
  refreshAll();
}
function doUndo() { const e = undo.pop(); if (!e) return; if (e.terrain) applyTerrain(e.terrain, 0); else restore(e.before); redo.push(e); refreshAll(); }
function doRedo() { const e = redo.pop(); if (!e) return; if (e.terrain) applyTerrain(e.terrain, 1); else restore(e.after); undo.push(e); refreshAll(); }
function applyTerrain(changes, which) { // changes: Map idx -> [[oldH, oldB], [newH, newB]]
  let i0 = 1e9, j0 = 1e9, i1 = 0, j1 = 0;
  for (const [idx, v] of changes) { W.hm[idx] = v[which][0]; W.bm[idx] = v[which][1]; touched.add(idx); const i = idx % W.nx, j = (idx / W.nx) | 0; i0 = Math.min(i0, i); j0 = Math.min(j0, j); i1 = Math.max(i1, i); j1 = Math.max(j1, j); }
  dirty.terrain = true; renderTerrain([Math.max(0, i0 - 1), Math.max(0, j0 - 1), Math.min(W.nx - 1, i1 + 1), Math.min(W.nz - 1, j1 + 1)]); redraw();
}

// ---------------------------------------------------------------- picking
function pick(wx, wz) {
  const tol = 9 / view.s;
  let best = null, bd = tol;
  const test = (layer, list, gx, gz) => { for (const o of list) { const d = Math.hypot(gx(o) - wx, gz(o) - wz); if (d < bd) { bd = d; best = { layer, ref: o }; } } };
  if (layers.spawns) test('spawns', D.spawns, (o) => o.x, (o) => o.z);
  if (layers.npcs) test('npcs', D.npcs, (o) => o.X, (o) => o.Z);
  if (layers.objects) test('objects', D.objects, (o) => o.x, (o) => o.z);
  if (best) return best;
  if (layers.buildings) for (let i = D.buildings.length - 1; i >= 0; i--) { const b = D.buildings[i]; if (Math.abs(b.x - wx) <= b.w / 2 && Math.abs(b.z - wz) <= b.d / 2) return { layer: 'buildings', ref: b }; }
  if (layers.props) { bd = tol * 0.7; for (const list of [addProps, genProps]) for (const p of list) { if (p.del) continue; const d = Math.hypot(p.x - wx, p.z - wz); if (d < bd) { bd = d; best = { layer: 'props', ref: p }; } } }
  return best;
}
