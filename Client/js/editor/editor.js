function draw() {
  needDraw = false;
  if (!D) return;
  const s = view.s * devicePixelRatio / devicePixelRatio; // view.s is in canvas px per metre
  ctx.fillStyle = '#0b2233'; ctx.fillRect(0, 0, cv.width, cv.height);
  if (layers.terrain) {
    ctx.imageSmoothingEnabled = false;
    const [x0, y0] = w2s(W.x0 - W.cell / 2, W.z0 - W.cell / 2);
    ctx.drawImage(tcv, x0, y0, W.nx * W.cell * s, W.nz * W.cell * s);
  }
  const sc = D.scenery;
  if (layers.roads) {
    ctx.lineCap = 'round'; ctx.strokeStyle = '#b89a62'; ctx.lineWidth = Math.max(1, 3.5 * s);
    for (const r of sc.roads) { ctx.beginPath(); r.forEach((p, i) => { const [x, y] = w2s(p[0], p[1]); i ? ctx.lineTo(x, y) : ctx.moveTo(x, y); }); ctx.stroke(); }
    for (const r of sc.rivers) { ctx.strokeStyle = r.k === 'lava' ? '#ff5a1a' : '#3a86c0'; ctx.lineWidth = Math.max(1, r.w * 1.6 * s); ctx.beginPath(); r.pts.forEach((p, i) => { const [x, y] = w2s(p[0], p[1]); i ? ctx.lineTo(x, y) : ctx.moveTo(x, y); }); ctx.stroke(); }
  }
  if (layers.buildings) {
    for (const b of D.buildings) {
      const [x, y] = w2s(b.x, b.z), ww = b.w * s, dd = b.d * s;
      ctx.fillStyle = b.k === 'wall' ? '#777' : b.k === 'pad' || b.k === 'dock' ? '#7a5a30' : b.k === 'pond' ? '#3a86c0aa' : '#c9a779';
      ctx.fillRect(x - ww / 2, y - dd / 2, ww, dd);
      ctx.strokeStyle = '#000a'; ctx.lineWidth = 1; ctx.strokeRect(x - ww / 2, y - dd / 2, ww, dd);
    }
  }
  if (layers.props && view.s > 0.6) {
    const r = Math.max(1, view.s * 0.9);
    for (const list of [genProps, addProps]) for (const p of list) {
      if (p.del) continue;
      const [x, y] = w2s(p.x, p.z);
      if (x < -5 || y < -5 || x > cv.width + 5 || y > cv.height + 5) continue;
      ctx.fillStyle = propCol(p.k);
      if (p.solid > 0) { ctx.beginPath(); ctx.arc(x, y, Math.max(1.2, p.solid * p.s * s * 0.8), 0, 6.3); ctx.fill(); } else ctx.fillRect(x - r / 2, y - r / 2, r, r);
    }
  }
  if (layers.towns) {
    ctx.font = `${12 * devicePixelRatio}px sans-serif`; ctx.textAlign = 'center';
    for (const t of sc.towns) { const [x, y] = w2s(t.x, t.z); ctx.fillStyle = '#fff'; ctx.strokeStyle = '#000'; ctx.lineWidth = 3; ctx.strokeText(t.name, x, y - 6); ctx.fillText(t.name, x, y - 6); }
  }
  if (layers.objects) for (const o of D.objects) mark(o.x, o.z, '#7bd88f', 'diamond', o.obj, o);
  if (layers.spawns) for (const sp of D.spawns) {
    const [x, y] = w2s(sp.x, sp.z);
    if (layers.aggro || sel?.ref === sp) { ctx.strokeStyle = '#ff5a4a88'; ctx.lineWidth = 1; ctx.beginPath(); ctx.arc(x, y, 8 * s, 0, 6.3); ctx.stroke(); ctx.strokeStyle = '#ffd66b66'; ctx.beginPath(); ctx.arc(x, y, 14 / 2 * s, 0, 6.3); ctx.stroke(); }
    mark(sp.x, sp.z, `hsl(${hue(sp.mob)} 80% 60%)`, 'circle', sp.mob, sp);
  }
  if (layers.npcs) for (const n of D.npcs) mark(n.X, n.Z, '#ffd66b', 'star', n.Name, n);
  if (tool !== 'select' && hover) previewCursor();
}
function mark(x, z, col, shape, label, ref) {
  const [sx, sy] = w2s(x, z);
  if (sx < -20 || sy < -20 || sx > cv.width + 20 || sy > cv.height + 20) return;
  const r = Math.max(3, Math.min(9, view.s * 2.2)) * devicePixelRatio / devicePixelRatio;
  ctx.fillStyle = col; ctx.strokeStyle = sel?.ref === ref ? '#fff' : '#000'; ctx.lineWidth = sel?.ref === ref ? 3 : 1.5;
  ctx.beginPath();
  if (shape === 'circle') ctx.arc(sx, sy, r, 0, 6.3);
  else if (shape === 'diamond') { ctx.moveTo(sx, sy - r * 1.2); ctx.lineTo(sx + r * 1.2, sy); ctx.lineTo(sx, sy + r * 1.2); ctx.lineTo(sx - r * 1.2, sy); ctx.closePath(); }
  else for (let i = 0; i < 10; i++) { const a = i * Math.PI / 5 - Math.PI / 2, rr = i % 2 ? r * 0.55 : r * 1.3; ctx.lineTo(sx + Math.cos(a) * rr, sy + Math.sin(a) * rr); }
  ctx.fill(); ctx.stroke();
  if (view.s > 3) { ctx.font = `${11 * devicePixelRatio}px sans-serif`; ctx.fillStyle = '#fff'; ctx.textAlign = 'left'; ctx.fillText(label, sx + r + 3, sy + 4); }
}
