function runChecks() {
  const out = [];
  const ww = (x, z) => { const h = cellAt(x, z); return h === null || h < 0.8; };
  D.spawns.forEach((s, i) => {
    if (ww(s.x, s.z)) out.push({ level: 'bad', text: `Spawn ${s.mob} steht im Wasser/außerhalb (${s.x.toFixed(0)}, ${s.z.toFixed(0)})`, at: [s.x, s.z] });
    for (let j = i + 1; j < D.spawns.length; j++) { const o = D.spawns[j]; if (Math.hypot(o.x - s.x, o.z - s.z) < 6.5 && !D.mobs[s.mob]?.Boss && !D.mobs[o.mob]?.Boss) { out.push({ level: 'warn', text: `Spawns ${s.mob} / ${o.mob} stehen nur ${Math.hypot(o.x - s.x, o.z - s.z).toFixed(1)} m auseinander (Gruppen-Pull)`, at: [s.x, s.z] }); break; } }
  });
  D.objects.forEach((o) => { if (ww(o.x, o.z)) out.push({ level: 'warn', text: `Objekt ${o.obj} im Wasser (${o.x.toFixed(0)}, ${o.z.toFixed(0)})`, at: [o.x, o.z] }); });
  D.npcs.forEach((n) => { if (ww(n.X, n.Z)) out.push({ level: 'bad', text: `NPC ${n.Name} steht im Wasser`, at: [n.X, n.Z] }); });
  for (const q of Object.values(D.quests)) {
    for (const o of q.objectives || []) {
      if (o.kind === 'kill' && !D.mobs[o.target]) out.push({ level: 'bad', text: `Quest „${q.title}“: Mob „${o.target}“ existiert nicht` });
      else if (o.kind === 'kill' && !D.spawns.some((s) => s.mob === o.target) && !D.dungeonMobs?.includes(o.target)) out.push({ level: 'warn', text: `Quest „${q.title}“: Mob „${o.target}“ hat keinen Spawn in der offenen Welt (ok, wenn Dungeon-Mob)` });
    }
    if (q.giver && !D.npcs.some((n) => n.ID === q.giver)) out.push({ level: 'bad', text: `Quest „${q.title}“: Geber-NPC „${q.giver}“ existiert nicht` });
  }
  for (const [id, m] of Object.entries(D.mobs)) if (!m.Name || m.LevelMin < 1) out.push({ level: 'bad', text: `Mob ${id}: Name/Level ungültig` });
  return out;
}
