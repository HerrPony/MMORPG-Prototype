function renderTerrain(region) {
  if (!timg || timg.width !== W.nx) { tcv.width = W.nx; tcv.height = W.nz; timg = tcv.getContext('2d').createImageData(W.nx, W.nz); }
  if (!BIOME_RGB.length) for (const z of D.zones) { const n = parseInt(z.color.slice(1), 16); BIOME_RGB[z.id] = [n >> 16, (n >> 8) & 255, n & 255]; }
  const [i0, j0, i1, j1] = region || [0, 0, W.nx - 1, W.nz - 1];
  for (let j = j0; j <= j1; j++) for (let i = i0; i <= i1; i++) {
    const idx = j * W.nx + i, h = W.hm[idx], b = W.bm[idx];
    const hl = W.hm[idx - (i > 0 ? 1 : 0)], hu = W.hm[idx - (j > 0 ? W.nx : 0)];
    const sh = Math.max(0.55, Math.min(1.45, 1 + ((hl - h) + (hu - h)) * 0.35));
    let c = BIOME_RGB[b] || [80, 80, 80];
    if (h < 0 && b !== 10) { const d = Math.min(1, -h / 7); c = [40 - d * 25, 110 - d * 55, 160 - d * 60]; }
    const o = idx * 4;
    timg.data[o] = Math.min(255, c[0] * sh); timg.data[o + 1] = Math.min(255, c[1] * sh); timg.data[o + 2] = Math.min(255, c[2] * sh); timg.data[o + 3] = 255;
  }
  tcv.getContext('2d').putImageData(timg, 0, 0);
}

